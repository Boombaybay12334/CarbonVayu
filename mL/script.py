"""
upload_to_supabase.py
=====================
Fills the four existing Supabase tables from pipeline CSV outputs.

Tables filled:
  states           ← VT_scores_final.csv
  vt_history       ← VT_scores_final.csv  (year=2022 snapshot)
  carbon_relations ← fine_claims.csv       (relation_type='fine',      status='fine_pending')
                   ← attribution_network.csv (relation_type='transport', status='neutral'/'fine_pending')
  projects         ← not generated by pipeline; skipped (fill manually)

Setup:
  pip install supabase python-dotenv
  Create a .env file:
    SUPABASE_URL=https://xxxx.supabase.co
    SUPABASE_KEY=your-service-role-key

Run:
  python upload_to_supabase.py
"""

import os
import sys
import math
from pathlib import Path

import pandas as pd
from dotenv import load_dotenv
from supabase import create_client, Client

# ---------------------------------------------------------------------------
# Config
# ---------------------------------------------------------------------------

load_dotenv()

SUPABASE_URL: str = os.environ.get("SUPABASE_URL", "")
SUPABASE_KEY: str = os.environ.get("SUPABASE_KEY", "")  # must be service-role key

if not SUPABASE_URL or not SUPABASE_KEY:
    sys.exit(
        "ERROR: Set SUPABASE_URL and SUPABASE_KEY in your environment or .env file.\n"
        "Use the service-role key (not the anon key) so writes are allowed."
    )

# Folder where pipeline writes its CSVs (outputs/ next to the pipeline script)
OUTPUT_DIR = Path(__file__).resolve().parent / "outputs"

