ECOSYSTEM_LABEL = {"F": "forest", "I": "industrial", "M": "mixed"}

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def load_csv(filename: str) -> pd.DataFrame:
    path = OUTPUT_DIR / filename
    if not path.exists():
        print(f"  [SKIP] {filename} not found at {path}")
        return pd.DataFrame()
    df = pd.read_csv(path)
    print(f"  [OK]   {filename}  ({len(df)} rows)")
    return df


def clean(val):
    """Replace NaN / inf with None so Supabase (JSON) accepts the payload."""
    if val is None:
        return None
    try:
        f = float(val)
        if math.isnan(f) or math.isinf(f):
            return None
    except (TypeError, ValueError):
        pass
    return val


def sanitise(records: list[dict]) -> list[dict]:
    return [{k: clean(v) for k, v in row.items()} for row in records]


def upsert(supabase: Client, table: str, rows: list[dict], chunk: int = 100):
    if not rows:
        print(f"  [SKIP] {table}: nothing to upsert")
        return
    total = len(rows)
    done = 0
    for start in range(0, total, chunk):
        batch = rows[start : start + chunk]
        supabase.table(table).upsert(batch).execute()
        done += len(batch)
        print(f"  {table}: {done}/{total}", end="\r")
    print(f"  [DONE] {table}: {total} rows upserted          ")


